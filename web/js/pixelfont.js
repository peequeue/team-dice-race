const GLYPHS = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(' ')]));

/** Width in pixels of a string at a given scale (5px glyph + 1px gap). */
export function pixelTextWidth(s, scale = 1) {
  return Math.max(0, String(s).length * 6 * scale - scale);
}

/**
 * Draws upper-case pixel text. (x, y) is the top-left for align 'left', the top-centre for 'center'.
 * shadow: a colour drawn one scaled pixel down and right first.
 */
export function pixelText(g, s, x, y, color, { scale = 1, align = 'left', shadow = null } = {}) {
  const str = String(s).toUpperCase();
  const w = pixelTextWidth(str, scale);
  let cx = Math.round(align === 'center' ? x - w / 2 : align === 'right' ? x - w : x);
  const cy = Math.round(y);
  const draw = (ox, oy, c) => {
    g.fillStyle = c;
    let gx = cx + ox;
    for (const ch of str) {
      const rows = GLYPHS[ch] ?? GLYPHS['?'];
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < 5; rx++) if (row[rx] === '1') g.fillRect(gx + rx * scale, cy + oy + ry * scale, scale, scale);
      });
      gx += 6 * scale;
    }
  };
  if (shadow) draw(scale, scale, shadow);
  draw(0, 0, color);
}
